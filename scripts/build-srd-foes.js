// scripts/build-srd-foes.js — builds public/srd-foes.js from netlify/functions/lib/srd-monsters.json
// (SRD 5.1, CC BY 4.0). The app reveals a foe in tiers: what anyone sees (size and type), what a
// successful Perception/Insight/Investigation check shows (AC, speed, senses), and what a successful
// knowledge check knows (resistances, immunities, special traits, languages).
//   node scripts/build-srd-foes.js
const fs = require("fs");
const path = require("path");
const MONSTERS = require("../netlify/functions/lib/srd-monsters.json");

const grab = (sb, re) => { const m = re.exec(sb); return m ? m[1].trim().replace(/\s+/g, " ") : ""; };
const out = {};
for (const { n, cr, sb } of MONSTERS) {
  const head = sb.split(" Armor Class")[0];
  const type = head.replace(/,\s*[^,]*$/, "").trim();                 // drop the alignment
  const ac = grab(sb, /Armor Class (\d+(?: \([^)]*\))?)/);
  const speed = grab(sb, /Speed (.*?) STR\b/);
  const senses = grab(sb, /Senses (.*?) (?:Languages|Challenge)\b/);
  const languages = grab(sb, /Languages (.*?) Challenge\b/);
  const vuln = grab(sb, /Damage Vulnerabilities (.*?) (?:Damage Resistances|Damage Immunities|Condition Immunities|Senses)\b/);
  const resist = grab(sb, /Damage Resistances (.*?) (?:Damage Immunities|Condition Immunities|Senses)\b/);
  const immune = grab(sb, /Damage Immunities (.*?) (?:Condition Immunities|Senses)\b/);
  const condImm = grab(sb, /Condition Immunities (.*?) Senses\b/);
  // Special traits: between the challenge rating and the actions; first sentence of each, at most 3.
  const traitText = grab(sb, /Challenge [^)]*\)\s*(.*?)\s+Actions\b/);
  const traits = [];
  if (traitText) {
    // Trait names are title-style ("Pack Tactics", "Keen Hearing and Smell", "Legendary Resistance (3/Day)").
    const NAME = String.raw`[A-Z][A-Za-z'’\-]*(?: (?:[A-Z][A-Za-z'’\-]*|of|and|the|to|in|from|with|or))*(?: \([^)]*\))?`;
    for (const part of traitText.split(new RegExp(String.raw`(?<=\.)\s+(?=${NAME}\.\s)`))) {
      const m = new RegExp(String.raw`^(${NAME})\.\s+(.*)$`).exec(part.trim());
      if (!m) continue;
      const first = (m[2].match(/^.*?[.!?](?=\s|$)/) || [m[2]])[0];
      traits.push(`${m[1].replace(/ \([^)]*\)$/, "")}: ${first.length > 170 ? first.slice(0, 167) + "..." : first}`);
      if (traits.length >= 3) break;
    }
  }
  out[n.toLowerCase()] = {
    n, cr, see: type,
    look: [ac && `AC ${ac}`, speed && `Speed ${speed}`, senses && `Senses: ${senses}`].filter(Boolean).join(" · "),
    lore: [vuln && `Vulnerable to ${vuln}`, resist && `Resists ${resist}`, immune && `Immune to ${immune}`,
      condImm && `Unaffected by: ${condImm}`, ...traits, languages && !/^[-—–]+$/.test(languages) && `Speaks: ${languages}`].filter(Boolean).join(" · "),
  };
}
const file = path.join(__dirname, "..", "public", "srd-foes.js");
fs.writeFileSync(file, `// Generated by scripts/build-srd-foes.js from the SRD 5.1 monster list (CC BY 4.0). Do not edit by hand.
// For each monster: see (anyone), look (after a Perception/Insight/Investigation check), lore (after a knowledge check).
window.SRD_FOES = ${JSON.stringify(out)};
`);
console.log(`wrote ${Object.keys(out).length} monsters to public/srd-foes.js (${Math.round(fs.statSync(file).size / 1024)} KB)`);
