// scripts/build-srd-xp.js
//
// Writes public/srd-xp.js: small name -> XP and name -> hit points tables from the SRD 5.1 monster list
// (netlify/functions/lib/srd-monsters.json, CC BY 4.0), so the app can award kill XP itself
// instead of trusting a number from the GM. Re-run after changing the monster list:
//   node scripts/build-srd-xp.js

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const monsters = require(path.join(root, "netlify", "functions", "lib", "srd-monsters.json"));
const table = {};
const hp = {};
for (const m of monsters) {
  if (!m || !m.n) continue;
  const key = String(m.n).toLowerCase();
  if (Number.isFinite(m.xp)) table[key] = m.xp;
  const h = /Hit Points (\d+)/.exec(m.sb || "");
  if (h) hp[key] = parseInt(h[1], 10);
}
const out = `// Generated by scripts/build-srd-xp.js from the SRD 5.1 monster list (CC BY 4.0). Do not edit by hand.
window.SRD_XP = ${JSON.stringify(table)};
window.SRD_HP = ${JSON.stringify(hp)};
`;
fs.writeFileSync(path.join(root, "public", "srd-xp.js"), out);
console.log(`Wrote public/srd-xp.js (${Object.keys(table).length} creatures, ${out.length} bytes).`);
